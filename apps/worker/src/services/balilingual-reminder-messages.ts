import type { Message } from '@line-crm/line-sdk';

export type BalilingualReminderStage = '24h' | '5d' | '14d';

// バリ島留学センター方針:
// - 面談予約は極力避け、LINEチャット + 見積もりで成約導線を作る
// - 沈黙ユーザーには段階的に価値訴求 → 申込ハードル下げ → 沈黙撤退の3段階
export function buildBalilingualEstimateReminderMessage(
  stage: BalilingualReminderStage,
  _friendId: string,
): Message {
  if (stage === '24h') {
    // 24時間後: 価値訴求 + 質問例で返信誘発
    return {
      type: 'text',
      text: [
        'バリ留学を検討中の方からよく聞かれる質問にお答えします🌴',
        '',
        'Q. 短期でも英語は伸びる?',
        'A. 1日4〜6時間の授業+生活すべて英語で、初心者から日常会話レベルまで上がる方が多いです。',
        '',
        'Q. 治安や生活は?',
        'A. チャングーは観光地で日本人スタッフ常駐、Wi-Fi完備で安心です。',
        '',
        'Q. 予算は?',
        'A. 期間と部屋スタイルでカスタムできます。気軽に「○週間で見積もり」と送ってください😊',
        '',
        '他にも疑問あればこのままLINEで質問してください✨',
        '',
        '💬 メッセージを送るには、画面左下のキーボードアイコンをタップしてください',
      ].join('\n'),
    };
  }

  if (stage === '5d') {
    // 5日後: 申込ハードル下げ + 仮押さえ案内
    return {
      type: 'text',
      text: [
        'ご検討ありがとうございます😊',
        '',
        '「いきなり申し込みは不安」という方は、まず仮押さえ(キャンセル可)からでもOKです。',
        '',
        '仮押さえの流れ:',
        '1. ご希望時期・期間をLINEで教えてください',
        '2. 空き状況と最終見積もりをお返しします',
        '3. 5万円のデポジットを銀行振込で送金 → 仮予約完了',
        '   (渡航60日前まで全額返金、本予約時は全額充当)',
        '',
        'キャンセル規定もご案内できます。お気軽にどうぞ✨',
        '',
        '💬 メッセージを送るには、画面左下のキーボードアイコンをタップしてください',
      ].join('\n'),
    };
  }

  // 14d: 沈黙撤退
  return {
    type: 'text',
    text: [
      'バリ島留学センターです🌴',
      '',
      'お返事がしばらく無いようなので、こちらからの定期メッセージは一旦お休みします😊',
      '',
      'また気になることが出てきたら、いつでもこのLINEに送ってください。',
      '・「○週間で見積もり」',
      '・「○月に行きたい」',
      '・「初心者でも大丈夫?」',
      '',
      'など、何でもお答えします✨',
    ].join('\n'),
  };
}
